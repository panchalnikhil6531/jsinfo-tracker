// Regenerates extension/lessons.js (the slugs the extension should track) from public/data.js.
// Run after editing the curriculum:  node extension/generate-lessons.js
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const src = fs.readFileSync(path.join(__dirname, "..", "public", "data.js"), "utf8");
const ctx = {};
vm.runInNewContext(src + "\nthis.CURRICULUM = CURRICULUM;", ctx);
const slugs = ctx.CURRICULUM.flatMap((p) => p.chapters.flatMap((c) => c.lessons.map((l) => l[1])));
fs.writeFileSync(
  path.join(__dirname, "lessons.js"),
  `// Generated by generate-lessons.js — do not edit.\nconst TRACKED_SLUGS = new Set(${JSON.stringify(slugs)});\n`
);
console.log(`Wrote ${slugs.length} slugs`);
